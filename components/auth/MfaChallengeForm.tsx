"use client";

import { useState, useRef, useEffect, Suspense } from "react";
import { useSearchParams, useRouter } from "next/navigation";
import { motion, AnimatePresence } from "framer-motion";
import { ShieldCheck, KeyRound, ArrowRight, Loader2, RefreshCcw } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import Link from "next/link";

function MfaChallengeFormInner() {
  const searchParams = useSearchParams();
  const router = useRouter();

  const challengeToken = searchParams.get("challenge") || "";
  const returnTo = searchParams.get("returnTo") || "/dashboard";

  const [digits, setDigits] = useState(["", "", "", "", "", ""]);
  const [isRecoveryMode, setIsRecoveryMode] = useState(false);
  const [recoveryCode, setRecoveryCode] = useState("");
  const [isLoading, setIsLoading] = useState(false);
  const [serverError, setServerError] = useState<string | null>(null);
  const [remainingAttempts, setRemainingAttempts] = useState<number | null>(null);

  const inputRefs = useRef<(HTMLInputElement | null)[]>([]);

  useEffect(() => {
    if (!isRecoveryMode) {
      inputRefs.current[0]?.focus();
    }
  }, [isRecoveryMode]);

  const handleDigitChange = (index: number, value: string) => {
    // Only accept numeric input
    const clean = value.replace(/[^0-9]/g, "");
    if (!clean) {
      const updated = [...digits];
      updated[index] = "";
      setDigits(updated);
      return;
    }

    const char = clean.slice(-1);
    const updated = [...digits];
    updated[index] = char;
    setDigits(updated);

    // Auto-advance to next input
    if (index < 5) {
      inputRefs.current[index + 1]?.focus();
    } else {
      // If 6th digit filled, auto submit
      const fullCode = updated.join("");
      if (fullCode.length === 6) {
        verifyCode(fullCode, false);
      }
    }
  };

  const handleKeyDown = (index: number, e: React.KeyboardEvent<HTMLInputElement>) => {
    if (e.key === "Backspace" && !digits[index] && index > 0) {
      inputRefs.current[index - 1]?.focus();
    }
  };

  const handlePaste = (e: React.ClipboardEvent<HTMLInputElement>) => {
    e.preventDefault();
    const pasted = e.clipboardData.getData("text").replace(/\D/g, "").slice(0, 6);
    if (pasted.length === 0) return;

    const updated = [...digits];
    for (let i = 0; i < 6; i++) {
      updated[i] = pasted[i] || "";
    }
    setDigits(updated);

    if (pasted.length === 6) {
      inputRefs.current[5]?.focus();
      verifyCode(pasted, false);
    } else {
      inputRefs.current[pasted.length]?.focus();
    }
  };

  const verifyCode = async (codeToVerify: string, isRecovery: boolean) => {
    if (!challengeToken) {
      setServerError("Invalid or missing authentication challenge. Please sign in again.");
      return;
    }

    setIsLoading(true);
    setServerError(null);

    try {
      const res = await fetch("/api/auth/mfa/challenge", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          challengeToken,
          code: codeToVerify,
          isRecoveryCode: isRecovery,
        }),
      });

      const data = await res.json();

      if (!res.ok) {
        setServerError(data.error || "Verification failed. Please try again.");
        if (data.remainingAttempts !== undefined) {
          setRemainingAttempts(data.remainingAttempts);
        }
        setIsLoading(false);
        return;
      }

      // Succeeded: navigate to destination
      router.replace(data.returnTo || returnTo);
    } catch {
      setServerError("Network error communicating with authentication service.");
      setIsLoading(false);
    }
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (isRecoveryMode) {
      verifyCode(recoveryCode, true);
    } else {
      verifyCode(digits.join(""), false);
    }
  };

  return (
    <div className="w-full max-w-md mx-auto space-y-6">
      <div className="space-y-2 text-center">
        <div className="inline-flex items-center justify-center h-12 w-12 rounded-xl bg-primary/10 text-primary mb-2 border border-primary/20">
          {isRecoveryMode ? <KeyRound className="h-6 w-6" /> : <ShieldCheck className="h-6 w-6" />}
        </div>
        <h1 className="text-2xl font-bold tracking-tight">Two-Factor Authentication</h1>
        <p className="text-sm text-muted-foreground">
          {isRecoveryMode
            ? "Enter one of your emergency backup recovery codes."
            : "Enter the 6-digit verification code generated by your Google Authenticator app."}
        </p>
      </div>

      <form onSubmit={handleSubmit} className="space-y-4">
        {!isRecoveryMode ? (
          <div className="space-y-2">
            <Label className="text-xs text-muted-foreground block text-center">Verification Code</Label>
            <div className="flex justify-center gap-2">
              {digits.map((digit, idx) => (
                <input
                  key={idx}
                  ref={(el) => {
                    inputRefs.current[idx] = el;
                  }}
                  type="text"
                  inputMode="numeric"
                  pattern="[0-9]*"
                  maxLength={1}
                  value={digit}
                  onChange={(e) => handleDigitChange(idx, e.target.value)}
                  onKeyDown={(e) => handleKeyDown(idx, e)}
                  onPaste={handlePaste}
                  disabled={isLoading}
                  className="w-12 h-14 text-center text-xl font-bold rounded-lg border border-border/80 bg-background/50 focus:border-primary focus:ring-2 focus:ring-primary/20 transition-all outline-hidden shadow-xs"
                />
              ))}
            </div>
          </div>
        ) : (
          <div className="space-y-2">
            <Label htmlFor="recoveryCode">Emergency Recovery Code</Label>
            <Input
              id="recoveryCode"
              placeholder="e.g. A1B2-C3D4"
              value={recoveryCode}
              onChange={(e) => setRecoveryCode(e.target.value.toUpperCase())}
              disabled={isLoading}
              className="h-11 font-mono tracking-wider text-center uppercase"
            />
          </div>
        )}

        <AnimatePresence mode="wait">
          {serverError && (
            <motion.div
              initial={{ opacity: 0, y: -6 }}
              animate={{ opacity: 1, y: 0 }}
              exit={{ opacity: 0, y: -6 }}
              className="p-3 text-xs sm:text-sm font-medium text-red-400 bg-red-500/10 border border-red-500/20 rounded-md text-center space-y-1"
            >
              <div>{serverError}</div>
              {remainingAttempts !== null && remainingAttempts > 0 && (
                <div className="text-xs text-red-400/80">
                  {remainingAttempts} attempt{remainingAttempts === 1 ? "" : "s"} remaining before challenge revocation.
                </div>
              )}
            </motion.div>
          )}
        </AnimatePresence>

        <Button
          type="submit"
          className="w-full h-10 font-semibold"
          disabled={isLoading || (!isRecoveryMode && digits.join("").length < 6) || (isRecoveryMode && !recoveryCode.trim())}
        >
          {isLoading ? (
            <Loader2 className="h-4 w-4 animate-spin mr-2" />
          ) : (
            <ArrowRight className="h-4 w-4 mr-2" />
          )}
          Verify and Sign In
        </Button>
      </form>

      <div className="pt-2 flex flex-col items-center gap-3 text-sm">
        <button
          type="button"
          onClick={() => {
            setIsRecoveryMode(!isRecoveryMode);
            setServerError(null);
          }}
          className="text-xs text-primary font-medium hover:underline flex items-center gap-1.5 transition-colors"
        >
          <RefreshCcw className="h-3.5 w-3.5" />
          {isRecoveryMode ? "Use authenticator app code instead" : "Don't have your device? Use recovery code"}
        </button>

        <Link href="/login" className="text-xs text-muted-foreground hover:text-foreground transition-colors">
          Return to sign in
        </Link>
      </div>
    </div>
  );
}

export function MfaChallengeForm() {
  return (
    <Suspense
      fallback={
        <div className="flex justify-center p-8">
          <Loader2 className="h-6 w-6 animate-spin text-muted-foreground" />
        </div>
      }
    >
      <MfaChallengeFormInner />
    </Suspense>
  );
}
